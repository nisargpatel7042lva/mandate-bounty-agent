// Writes generated/index.ts with ABIs and bytecode from Foundry's out/ directory.
// Run after `forge build` (the package `build` script does both).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const contracts = ["BountyVault", "MockUSDC"];
let src = "// Generated by gen-abi.mjs from forge build output. Do not edit.\n\n";
for (const name of contracts) {
  const artifact = JSON.parse(readFileSync(`out/${name}.sol/${name}.json`, "utf8"));
  const camel = name[0].toLowerCase() + name.slice(1);
  src += `export const ${camel}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
  src += `export const ${camel}Bytecode = "${artifact.bytecode.object}" as const;\n\n`;
}
mkdirSync("generated", { recursive: true });
writeFileSync("generated/index.ts", src);
console.log(`wrote generated/index.ts (${contracts.join(", ")})`);
